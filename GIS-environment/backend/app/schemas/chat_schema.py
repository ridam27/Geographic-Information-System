from pydantic import BaseModel, Field
from typing import List, Optional

class ChatMessageHistory(BaseModel):
    role: str = Field(..., description="Role of message author: 'user' or 'assistant' or 'system'")
    content: str = Field(..., description="Content of the message")

class ChatRequest(BaseModel):
    message: str = Field(..., description="User's natural language question")
    location: Optional[str] = Field(None, description="Optional target location name e.g. Nagpur")
    latitude: Optional[float] = Field(None, description="Optional target latitude")
    longitude: Optional[float] = Field(None, description="Optional target longitude")
    history: Optional[List[ChatMessageHistory]] = Field(default_factory=list, description="Conversation history for session memory")

class ChatSource(BaseModel):
    name: str = Field(..., description="Source system name e.g. Open-Meteo, USGS, NASA FIRMS, ML Storm Predictor")
    type: str = Field(..., description="Data category e.g. Weather, Earthquakes, Active Fires, ML Prediction")
    timestamp: Optional[str] = Field(None, description="ISO timestamp or freshness description of retrieved data")

class ResolvedLocation(BaseModel):
    name: str
    latitude: float
    longitude: float
    country: Optional[str] = None
    source: str

class ChatResponse(BaseModel):
    success: bool
    answer: str = Field(..., description="Natural language response generated by Groq based on real telemetry")
    sources: List[ChatSource] = Field(default_factory=list, description="Explicit data citations for transparency")
    location: Optional[ResolvedLocation] = Field(None, description="Resolved geographic context for the query")
    timestamp: str = Field(..., description="ISO 8601 server generation timestamp")
    error: Optional[str] = Field(None, description="Error message if processing failed")
